import type { Meta } from "@/lib/types";
import { BoltIcon, BroadcastIcon, ChipIcon, ClockIcon, CoinsIcon, SwapIcon } from "./icons";

const chip = "inline-flex items-center gap-1.5 rounded-full border px-2.5 py-1 text-[11.5px] font-medium leading-none whitespace-nowrap";

/** Per-response metadata required by the brief: source, model, latency, input/output tokens. */
export function MetaChips({ meta }: { meta: Meta }) {
  const cached = meta.source === "LLM_CACHE";
  return (
    <ul className="mt-2.5 flex flex-wrap gap-1.5" aria-label="Response details">
      <li
        className={`${chip} ${cached ? "border-good/30 bg-good-soft text-good" : "border-info/30 bg-info-soft text-info"}`}
        title={cached ? "Served from LiteLLM's response cache. No model call was made." : "Generated by a live model call."}
      >
        {cached ? <BoltIcon /> : <BroadcastIcon />}
        <span className="sr-only">Resolution source: </span>
        {meta.source}
      </li>
      <li className={`${chip} border-line bg-surface-2 text-fg`} title="Model that produced this answer">
        <ChipIcon />
        <span className="sr-only">Model: </span>
        <span className="font-mono">{meta.model}</span>
      </li>
      <li className={`${chip} border-line bg-surface-2 text-fg`} title="Server-side response time for this request">
        <ClockIcon />
        <span className="sr-only">Latency: </span>
        {meta.latency_ms.toLocaleString()} ms
      </li>
      <li
        className={`${chip} border-line bg-surface-2 text-fg`}
        title={
          cached
            ? "Token counts from the original generation. Nothing new was consumed or billed for this cached reply."
            : "Tokens consumed by this single request"
        }
      >
        <CoinsIcon />
        <span className="sr-only">Token usage: </span>
        <span>
          {meta.input_tokens.toLocaleString()} in · {meta.output_tokens.toLocaleString()} out
        </span>
        {cached && <span className="text-muted">· 0 billed</span>}
      </li>
      {meta.fallback_used && (
        <li
          className={`${chip} border-warn/30 bg-warn-soft text-warn`}
          title="The preferred key was rate-limited, over quota or failing, so the gateway switched to a backup key automatically."
        >
          <SwapIcon />
          Answered via backup key{meta.served_by ? ` · ${meta.served_by}` : ""}
        </li>
      )}
    </ul>
  );
}
